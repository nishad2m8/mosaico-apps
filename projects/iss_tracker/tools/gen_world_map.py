"""Convert world-atlas TopoJSON into C polylines for the globe renderer.

Usage: python tools/gen_world_map.py tools/data/countries-110m.json main/world_map_data.c

Emits coastlines (rings of the `land` object) and internal borders (arcs shared
by two different countries) as int16 longitude/latitude in 1/100 degree, plus
country rings in 1/50 degree for "which country is below" lookups. Country
rings that cross the antimeridian are unwrapped to longitudes in 0..360.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

LINE_SCALE = 100
COUNTRY_SCALE = 50


def decode_arcs(topo: dict) -> list[list[tuple[float, float]]]:
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:
        x = y = 0
        points = []
        for dx, dy in arc:
            x += dx
            y += dy
            points.append((x * sx + tx, y * sy + ty))
        arcs.append(points)
    return arcs


def polygons(geometry: dict) -> list[list[list[int]]]:
    if geometry["type"] == "Polygon":
        return [geometry["arcs"]]
    if geometry["type"] == "MultiPolygon":
        return geometry["arcs"]
    return []


def ring_points(arcs, refs: list[int]) -> list[tuple[float, float]]:
    out: list[tuple[float, float]] = []
    for ref in refs:
        pts = arcs[ref] if ref >= 0 else list(reversed(arcs[~ref]))
        out.extend(pts if not out else pts[1:])
    return out


def main() -> int:
    src, dst = Path(sys.argv[1]), Path(sys.argv[2])
    topo = json.loads(src.read_text())
    arcs = decode_arcs(topo)

    coast = []
    for geom in topo["objects"]["land"]["geometries"]:
        for poly in polygons(geom):
            for ring in poly:
                coast.append(ring_points(arcs, ring))

    owners: dict[int, set[int]] = {}
    for gi, geom in enumerate(topo["objects"]["countries"]["geometries"]):
        for poly in polygons(geom):
            for ring in poly:
                for ref in ring:
                    owners.setdefault(ref if ref >= 0 else ~ref, set()).add(gi)
    borders = [arcs[i] for i, who in sorted(owners.items()) if len(who) > 1]

    country_rings, country_first, country_count, names = [], [], [], []
    for geom in topo["objects"]["countries"]["geometries"]:
        rings = [ring_points(arcs, poly[0]) for poly in polygons(geom)]  # outer rings
        if not rings:
            continue
        names.append(geom["properties"]["name"])
        country_first.append(len(country_rings))
        country_count.append(len(rings))
        for ring in rings:
            lons = [lon for lon, _ in ring]
            crosses = any(abs(a - b) > 180 for a, b in zip(lons, lons[1:]))
            country_rings.append([((lon + 360) if crosses and lon < 0 else lon, lat) for lon, lat in ring])

    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by tools/gen_world_map.py from world-atlas countries-110m",
        "// (ISC; Natural Earth public-domain data). Do not edit.",
        "",
        '#include "world_map.h"',
        "",
    ]

    def emit(name: str, polylines, scale: int) -> None:
        pts, starts = [], []
        for pl in polylines:
            starts.append(len(pts))
            pts.extend((round(lon * scale), round(lat * scale)) for lon, lat in pl)
        starts.append(len(pts))
        lines.append(f"static const int16_t s_{name}_pts[][2] = {{")
        for i in range(0, len(pts), 6):
            lines.append("    " + " ".join(f"{{{a},{b}}}," for a, b in pts[i:i + 6]))
        lines.append("};")
        lines.append(f"static const uint32_t s_{name}_starts[] = {{")
        for i in range(0, len(starts), 12):
            lines.append("    " + " ".join(f"{s}," for s in starts[i:i + 12]))
        lines.append("};")
        lines.append(f"const world_map_set_t world_map_{name} = {{")
        lines.append(f"    .points = s_{name}_pts, .starts = s_{name}_starts,")
        lines.append(f"    .polyline_count = {len(polylines)}, .point_count = {len(pts)}, .scale = {scale},")
        lines.append("};")
        lines.append("")

    emit("coast", coast, LINE_SCALE)
    emit("borders", borders, LINE_SCALE)
    emit("country_rings", country_rings, COUNTRY_SCALE)

    lines.append("const world_map_country_t world_map_countries[] = {")
    for name, first, count in zip(names, country_first, country_count):
        lines.append(f"    {{{json.dumps(name, ensure_ascii=False)}, {first}, {count}}},")
    lines.append("};")
    lines.append(f"const uint32_t world_map_country_count = {len(names)};")
    lines.append("")
    dst.write_text("\n".join(lines))
    print(f"coast: {len(coast)} rings, borders: {len(borders)} arcs, "
          f"countries: {len(names)} -> {dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
